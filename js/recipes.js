// Per-serving numbers, computed from the ingredients.
export function perServing(r) {
  let kcal = 0, p = 0;
  for (const [id, g] of r.ing) { kcal += ING[id].kcal * g / 100; p += ING[id].p * g / 100; }
  return { kcal: Math.round(kcal / r.serves / 5) * 5, p: Math.round(p / r.serves) };
}
